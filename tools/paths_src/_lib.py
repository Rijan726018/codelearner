def slug(t): return re.sub(r"[^a-z0-9]+", "-", t.lower()).strip("-")[:48]

def N(t, d, topics=(), links=(), core=None, opt=False):
    out = {"id": slug(t), "t": t, "d": d, "topics": list(topics), "links": [list(L[x]) if isinstance(x, str) else list(x) for x in links]}
    if core: out["core"] = core
    if opt: out["opt"] = True
    return out

def PH(title, weeks, goal, nodes, project=None):
    ph = {"title": title, "weeks": weeks, "goal": goal, "nodes": nodes}
    if project: ph["project"] = {"t": project[0], "d": project[1]}
    return ph

